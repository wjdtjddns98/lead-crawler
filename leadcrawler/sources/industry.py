    stripped = (industry or "").strip()
    if not stripped:
        return False
    if stripped.casefold() in _TAXONOMY_CASEFOLD:
        return True
    return any(
        k in _EN_INDUSTRY or k in _KSIC or k in _SIC or k in _UK_SIC
        for k in _lookup_keys(industry)
    )


